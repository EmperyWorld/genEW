"""
Fortune Seaker - Registry Snippet Generator
Produces paste-ready moduleRegistry entry for imported modules
"""

import json
from typing import Any, Dict

from .naming import to_kebab, to_registry_const


def build_registry_snippet(
    module_name: str,
    module_type: str,
    import_manifest: Dict[str, Any],
) -> Dict[str, str]:
    """
    Build registry snippet file for manual or automated registration.
    """
    kebab_name = to_kebab(module_name)
    registry_key = kebab_name
    display_name = import_manifest.get("displayName", module_name)

    snippet = {
        registry_key: {
            "moduleType": module_type,
            "displayName": display_name,
            "description": f"Imported via Fortune Seaker ({import_manifest.get('source', 'zip')})",
            "compatVersion": import_manifest.get("compatVersion", "1.0.0"),
            "configSchema": import_manifest.get(
                "configSchema",
                "schemas/import-manifest.json",
            ),
            "generatorEntrypoint": import_manifest.get(
                "generatorEntrypoint",
                "generators/importer/prepare.py",
            ),
            "previewEntrypoint": import_manifest.get(
                "previewEntrypoint",
                "src/components/Generator/LivePreview.tsx",
            ),
            "exportRules": import_manifest.get(
                "exportRules",
                {"includePackageJson": True, "includeReadme": True},
            ),
        }
    }

    content = (
        "// Auto-generated by Fortune Seaker — paste into src/registry/moduleRegistry.ts\n"
        f"export const {to_registry_const(module_name)} = "
        f"{json.dumps(snippet, indent=2, ensure_ascii=False)} as const;\n"
    )

    return {
        "path": f"src/registry/snippets/imported-{kebab_name}.registry.ts",
        "content": content,
        "language": "typescript",
        "description": "Module registry snippet for Fortune Seaker import",
    }
