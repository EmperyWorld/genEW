/** Короткая подпись для title / подсказок у кнопок скачивания. */
export const CREATIVE_NON_COMMERCIAL_DOWNLOAD_HINT =
	'Только для личного некоммерческого использования. Коммерция без прав на использование запрещена.';

/** Полный текст подтверждения перед сохранением файла на устройство. */
export const CREATIVE_NON_COMMERCIAL_DOWNLOAD_CONFIRM =
	'Сгенерированный контент предназначен только для личного некоммерческого использования. Коммерческое использование (продажа, реклама, публичные показы и иное без соответствующих прав) не допускается, если иное не оговорено отдельно.\n\nПродолжить скачивание?';

export function confirmCreativeNonCommercialDownload(): boolean {
	if (typeof window === 'undefined') return true;
	return window.confirm(CREATIVE_NON_COMMERCIAL_DOWNLOAD_CONFIRM);
}

