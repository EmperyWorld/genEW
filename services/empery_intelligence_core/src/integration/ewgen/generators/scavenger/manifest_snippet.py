"""
Scavenger - Manifest index registration snippet
"""

import json
from typing import Any, Dict

from generators.importer.naming import to_kebab

from .manifest_index import build_index_entry


def build_manifest_registration_snippet(
    module_name: str,
    import_manifest: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Build a paste-ready entry for manifests/scavenger-imports.json.
    """
    kebab = to_kebab(module_name)
    index_entry = build_index_entry(module_name, import_manifest)
    entry = {kebab: {key: value for key, value in index_entry.items() if key != "registeredAt"}}

    lines = [
        "# Auto-generated by Scavenger — merge into manifests/scavenger-imports.json",
        "# Under the \"imports\" object, add or update:",
        json.dumps(entry, indent=2, ensure_ascii=False),
    ]

    return {
        "path": f"snippets/imported-python-{kebab}.manifest-index.snippet",
        "content": "\n".join(lines) + "\n",
        "language": "text",
        "description": "Manifest index entry for manifests/scavenger-imports.json",
        "indexEntry": index_entry,
    }
